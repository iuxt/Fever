export type Folder = { id: string; name: string; parentId: string | null };
export type FolderPlacement = { target: string; position: 'before' | 'after' };
export type StoredNote = { id: string; title: string; folderId: string | null; filename: string; createdAt: string; updatedAt: string; sourcePath?: string; directory?: 'notes' | 'drawings'; originalCategory?: string };
// Paths are derived for rendering and never written into the v2 manifest.
export type Note = StoredNote & { category: string };
export type StoredManifest = { version: 2; folders: Folder[]; notes: StoredNote[]; trash?: StoredNote[] };
export type Manifest = Omit<StoredManifest, 'notes' | 'trash'> & { categories: string[]; notes: Note[]; trash?: Note[] };
export type RevisionAsset = { id: string; hash: string; wiki?: boolean };
export type Vault = { path: string; name: string; manifest: Manifest; lfs: boolean };
export type SaveResult = { updatedAt: string };
export type Change = { status: string; path: string; staged: boolean; unstaged: boolean; originalPath?: string; stagedWhitespaceOnly?: boolean; unstagedWhitespaceOnly?: boolean };
export type FileDiff = { path: string; patch: string; whitespaceIgnoredPatch?: string };
export type VaultFile = { path: string; content: string; binary: boolean; image?: string };
export type GitStatus = { branch: string; head?: string; changes: Change[]; ahead: number; behind: number; remote: string; lfs: boolean };
export type Commit = { hash: string; author: string; date: string; message: string };
export type GitFileChange = { path: string; status: string; originalPath?: string };
export type CommitResult = { committed: boolean; restoredPaths: string[]; hash?: string; changes: GitFileChange[] };
export type PullResult = { before: string; after: string; commitCount: number; changes: GitFileChange[] };
export type PullRecord = PullResult & { pulledAt: string };
export type RevisionComparison = { content: string; previousContent: string; previousHash?: string };
export type Settings = { autoCommit: boolean; interval: number; autoPull: boolean; pullInterval: number; author: string; email: string; remote: string };
export type ExportFormat = 'pdf' | 'html' | 'md' | 'excalidraw';
export type ExportOptions = {
  format: ExportFormat;
  filename: string;
  pageSize: 'A4' | 'A3' | 'A5' | 'Letter';
  landscape: boolean;
  margin: number;
  fontSize: number;
  width: number;
};
export type Api = {
  desktop: boolean;
  exportNote?: (document: { format: ExportFormat; filename: string; content: string; pageSize?: ExportOptions['pageSize']; landscape?: boolean }) => Promise<'saved' | 'canceled'>;
  platform?: string;
  onCloseTab?: (callback: () => void) => () => void;
  readClipboard?: () => Promise<{ text: string; html?: string }>;
  writeClipboard?: (content: { text: string; html?: string }) => Promise<void>;
  current(): Promise<Vault | null>;
  open(): Promise<Vault | null>;
  read(id: string, scope?: 'trash'): Promise<string>;
  preview?(id: string, requestId: string): Promise<string>;
  cancelPreview?(requestId: string): Promise<void>;
  search(query: string, scope?: 'trash'): Promise<string[]>;
  cancelSearch(): Promise<void>;
  save(id: string, content: string): Promise<SaveResult | void>;
  flushMetadata?(): Promise<void>;
  onSaveError?: (callback: (message: string) => void) => () => void;
  create(title: string, category: string, format?: 'markdown' | 'excalidraw'): Promise<Note>;
  update(id: string, title: string, category: string): Promise<Note>;
  remove(id: string): Promise<void>;
  restoreTrash(id: string): Promise<Note>;
  category(path: string): Promise<void>;
  moveCategory(from: string, to: string, placement?: FolderPlacement): Promise<void>;
  removeCategory(path: string): Promise<void>;
  importNotes(): Promise<Note[]>;
  image(bytes: Uint8Array | number[], name: string, noteId: string, importId?: string): Promise<string>;
  completeImageImport(importId: string, keep: boolean): Promise<void>;
  localizeImages(urls: string[], noteId: string): Promise<{ replacements: Record<string, string>; failed: { url: string; message: string }[] }>;
  asset(src: string, revision?: RevisionAsset): string;
  status(inspectWhitespace?: boolean): Promise<GitStatus>;
  diff(path: string, staged?: boolean): Promise<FileDiff>;
  stage(path: string): Promise<void>;
  unstage(path: string): Promise<void>;
  stageAll(): Promise<void>;
  unstageAll(): Promise<void>;
  discard(path: string): Promise<void>;
  discardAll(): Promise<string[]>;
  openFile(path: string): Promise<VaultFile>;
  saveFile(path: string, content: string): Promise<SaveResult | void>;
  commit(message: string, stagedOnly?: boolean, ignoreWhitespace?: boolean): Promise<CommitResult>;
  preparePull(): Promise<string>;
  cancelPull(token: string): Promise<void>;
  pull(token?: string): Promise<PullResult>;
  pullDiff(before: string, after: string, path: string, originalPath?: string): Promise<FileDiff>;
  push(): Promise<void>;
  history(id?: string): Promise<Commit[]>;
  revision(id: string, hash: string): Promise<string>;
  revisionComparison(id: string, hash: string): Promise<RevisionComparison>;
  restore(id: string, hash: string): Promise<string>;
  settings(): Promise<Settings>;
  configure(settings: Settings): Promise<void>;
  onBackupError?: (callback: (message: string) => void) => () => void;
  onAutoPull?: (callback: () => void) => () => void;
};
