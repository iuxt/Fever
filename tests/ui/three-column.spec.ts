import { test, expect } from '@playwright/test';

test('folders scope the middle list, previews update, and search spans the vault', async ({ page }) => {
 const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
 await page.goto('/');
 await expect(page.getByLabel('文件夹栏')).toBeVisible();
 await expect(page.getByLabel('笔记列表栏')).toBeVisible();
 await expect(page.locator('.sidebar .note-row')).toHaveCount(0);
 await expect(page.locator('.inspector')).toHaveCount(0);
 await page.locator('.folder-row').filter({ hasText: '开始使用' }).click();
 await expect(page.locator('.note-card')).toHaveCount(2);
 await expect(page.locator('.file-list-header h2')).toHaveText('开始使用');
 await expect(page.locator('.note-card').first().locator('.note-card-preview')).toContainText('欢迎来到 Fever');
 await page.locator('.note-card').filter({ hasText: 'Markdown 语法指南' }).click();
 await expect(page.locator('.wysiwyg-content h1')).toHaveText('Markdown 语法指南');
 const folder = await page.getByLabel('文件夹栏').boundingBox();
 const list = await page.getByLabel('笔记列表栏').boundingBox();
 const editor = await page.locator('.workspace').boundingBox();
 expect(list!.x).toBe(folder!.x + folder!.width);
 expect(editor!.x).toBe(list!.x + list!.width);
 await page.locator('.wysiwyg-content').fill('这里是刚刚修改的摘要');
 await expect(page.locator('.note-card.selected .note-card-preview')).toHaveText('这里是刚刚修改的摘要');
 await page.locator('.folder-row').filter({ hasText: '知识管理' }).click();
 await expect(page.locator('.note-card')).toHaveCount(2);
 await expect(page.locator('.note-card').first()).toContainText('构建我的第二大脑');
 await expect(page.locator('.wysiwyg-content')).toContainText('这里是刚刚修改的摘要');
 await page.getByPlaceholder('搜索你的笔记…').fill('Markdown 语法指南');
 await expect(page.locator('.note-card')).toHaveCount(1);
 await page.locator('.note-card').click();
 await expect(page.locator('.wysiwyg-content')).toContainText('这里是刚刚修改的摘要');
 await page.getByPlaceholder('搜索你的笔记…').fill('');
 await page.locator('.all-notes').filter({ hasText: '全部笔记' }).click();
 await page.screenshot({ path: 'test-results/three-column-light.png', fullPage: true });
 await page.emulateMedia({ colorScheme: 'dark' });
 await page.screenshot({ path: 'test-results/three-column-dark.png', fullPage: true });
 await page.setViewportSize({ width: 780, height: 800 });
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
 await expect(page.locator('.wysiwyg-content')).toBeInViewport();
 expect(errors).toEqual([]);
});

test('parent folders include descendants and empty folders create notes in place', async ({ page }) => {
 await page.goto('/');
 await page.locator('.folder-row').filter({ hasText: /^项目/ }).click();
 await expect(page.locator('.note-card')).toHaveCount(2);
 await expect(page.locator('.folder-row').filter({ hasText: /^Fever/ })).toBeVisible();
 await page.locator('.folder-row').filter({ hasText: /^项目/ }).click({ button: 'right' });
 await page.getByRole('menuitem', { name: '折叠分类', exact: true }).click();
 await expect(page.locator('.folder-row').filter({ hasText: /^Fever/ })).toHaveCount(0);
 await expect(page.locator('.note-card')).toHaveCount(2);
 await page.getByTitle('新建分类', { exact: true }).click();
 await page.getByLabel('分类名称').fill('项目/空文件夹');
 await page.getByRole('button', { name: '创建分类', exact: true }).click();
 await expect(page.locator('.file-list-empty')).toContainText('这个文件夹还是空的');
 await page.getByRole('button', { name: '写下第一篇笔记' }).click();
 await expect(page.getByLabel('所属分类')).toHaveValue('项目/空文件夹');
 await page.getByLabel('笔记标题').fill('空文件夹里的笔记');
 await page.getByRole('button', { name: '创建笔记', exact: true }).click();
 await expect(page.locator('.note-card.selected')).toContainText('空文件夹里的笔记');
 await page.locator('.note-card.selected').click({ button: 'right' });
 await page.getByRole('menuitem', { name: '删除笔记', exact: true }).click();
 await page.getByRole('button', { name: '删除笔记', exact: true }).click();
 await page.getByRole('button', { name: /^回收站/ }).click();
 await expect(page.locator('.file-list-panel .trash-item')).toContainText('空文件夹里的笔记');
 await page.getByRole('button', { name: '恢复：空文件夹里的笔记', exact: true }).click();
 await expect(page.locator('.note-card.selected')).toContainText('空文件夹里的笔记');
});
