import { test, expect } from '@playwright/test';

test('Git file rows show differences, stage snapshots, open notes and confirm discard', async ({ page }) => {
 await page.goto('/');
 await page.getByTitle('Markdown 源码与预览', { exact: true }).click();
 await page.locator('.cm-content').fill('# staged snapshot\n\nfirst change');
 await expect(page.getByText('所有更改已保存')).toBeVisible();
 await page.getByRole('button', { name: 'Git', exact: true }).click();
 const row = page.locator('.change').filter({ hasText: '欢迎使用 Fever' });
 await row.getByRole('button', { name: '查看工作区差异：欢迎使用 Fever' }).click();
 await expect(page.locator('.diff-editor')).toContainText('+first change');
 await expect(page.locator('.diff-editor .diff-remove')).not.toHaveCount(0);
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.locator('.tab.current')).toContainText('欢迎使用 Fever · 工作区对比');
 await page.screenshot({ path: 'test-results/git-diff.png' });
 await page.getByTitle('关闭对比：notes/demo-1.md', { exact: true }).click();
 await row.getByTitle('暂存变更：notes/demo-1.md', { exact: true }).click();
 await expect(page.getByText('已暂存变更', { exact: true })).toBeVisible();
 await page.locator('.cm-content').fill('# working snapshot\n\nsecond change');
 await expect(page.getByText('所有更改已保存')).toBeVisible();
 await expect(row).toHaveCount(2);
 await page.getByRole('button', { name: '查看已暂存差异：欢迎使用 Fever' }).click();
 await expect(page.locator('.diff-editor')).toContainText('+first change');
 await expect(page.locator('.diff-editor')).not.toContainText('second change');
 await page.getByTitle('关闭对比：notes/demo-1.md', { exact: true }).click();
 await page.getByPlaceholder('这次记录了什么？').fill('stage only');
 await page.getByRole('button', { name: '提交已暂存变更 (1)', exact: true }).click();
 await expect(row).toHaveCount(1);
 await expect(page.locator('.cm-content')).toContainText('second change');
 await page.locator('.note-row').filter({ hasText: 'Markdown 语法指南' }).click();
 await row.getByTitle('打开文件：notes/demo-1.md', { exact: true }).click();
 await expect(page.locator('.wysiwyg-content')).toContainText('second change');
 await row.getByTitle('撤销变更：notes/demo-1.md', { exact: true }).click();
 await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click();
 await expect(page.locator('.wysiwyg-content')).toContainText('second change');
 await row.getByTitle('撤销变更：notes/demo-1.md', { exact: true }).click();
 await page.getByRole('dialog').getByRole('button', { name: '撤销变更', exact: true }).click();
 await expect(page.locator('.wysiwyg-content')).toContainText('first change');
 await expect(row).toHaveCount(0);
 await page.screenshot({ path: 'test-results/git-changes.png' });
});

test('unstaging retains edits and discarding a new note removes its library entry', async ({ page }) => {
 await page.goto('/');
 await page.getByRole('button', { name: '新建笔记', exact: true }).first().click();
 await page.getByLabel('笔记标题').fill('新文件');
 await page.getByRole('button', { name: '创建笔记', exact: true }).click();
 await page.getByRole('button', { name: 'Git', exact: true }).click();
 const row = page.locator('.change').filter({ hasText: '新文件' });
 await row.getByRole('button', { name: /^暂存变更：/ }).click();
 await row.getByRole('button', { name: /^取消暂存：/ }).click();
 await expect(page.getByText('已暂存变更', { exact: true })).toHaveCount(0);
 await expect(page.locator('.note-row.selected')).toContainText('新文件');
 await page.getByRole('button', { name: '查看工作区差异：fever.json' }).click();
 await expect(page.locator('.diff-editor')).toContainText('新文件');
 await page.getByTitle('关闭对比：fever.json', { exact: true }).click();
 await row.getByRole('button', { name: /^撤销变更：/ }).click();
 await page.getByRole('dialog').getByRole('button', { name: '撤销变更', exact: true }).click();
 await expect(page.locator('.note-row').filter({ hasText: '新文件' })).toHaveCount(0);
 await expect(row).toHaveCount(0);
 await page.reload();
 await expect(page.locator('.note-row').filter({ hasText: '新文件' })).toHaveCount(0);
});

test('repository text files open as editable tabs and save before switching to notes', async ({ page }) => {
 await page.goto('/');
 await page.getByTitle('Markdown 源码与预览', { exact: true }).click();
 await page.locator('.cm-content').fill('# Note kept during file navigation\n\nunsaved note');
 await page.getByRole('button', { name: 'Git', exact: true }).click();
 await page.getByTitle('刷新 Git 状态', { exact: true }).click();
 await page.getByTitle('打开文件：fever.json', { exact: true }).click();
 await expect(page.locator('.tab.current')).toContainText('fever.json');
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.locator('.file-editor .cm-content')).toContainText('demo-1.md');
 const state = await page.evaluate(() => JSON.parse(localStorage.getItem('fever-demo-v1')!));
 state.manifest.categories.push('源码文件编辑');
 await page.locator('.file-editor .cm-content').fill(JSON.stringify(state.manifest, null, 2));
 // Switching immediately must flush the file's pending edit, just like note edits.
 await page.locator('.tab').filter({ hasText: '欢迎使用 Fever' }).getByRole('button', { name: '欢迎使用 Fever', exact: true }).click();
 await expect(page.locator('.cm-content')).toContainText('unsaved note');
 await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('fever-demo-v1')!).manifest.categories)).toContain('源码文件编辑');
 await page.locator('.tab').getByRole('button', { name: 'fever.json', exact: true }).click();
 await expect(page.locator('.file-editor .cm-content')).toContainText('源码文件编辑');
 await page.screenshot({ path: 'test-results/git-file-editor.png' });
 await page.getByTitle('关闭文件：fever.json', { exact: true }).click();
 await expect(page.locator('.cm-content')).toContainText('unsaved note');
 await page.getByTitle('打开文件：fever.json', { exact: true }).click();
 await page.getByTitle('撤销变更：notes/demo-1.md', { exact: true }).click();
 await page.getByRole('dialog').getByRole('button', { name: '撤销变更', exact: true }).click();
 await expect(page.locator('.tab.current')).toContainText('fever.json');
 await page.getByTitle('关闭文件：fever.json', { exact: true }).click();
 await expect(page.locator('.cm-content')).toContainText('让每一个想法，都有迹可循。');
 await expect(page.locator('.cm-content')).not.toContainText('unsaved note');
});
