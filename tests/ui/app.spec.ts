 await expect(page.locator('.drawing-canvas .excalidraw')).toBeVisible();
 const canvas = page.locator('.drawing-canvas canvas.interactive');
 await canvas.click(); await page.keyboard.press('r');
 const box = (await canvas.boundingBox())!;
 await page.mouse.move(box.x + 330, box.y + 180); await page.mouse.down();
 await page.mouse.move(box.x + 510, box.y + 280, { steps: 6 }); await page.mouse.up();
 await page.keyboard.press('t'); await page.mouse.click(box.x + 330, box.y + 340);
 await page.locator('.excalidraw-wysiwyg').fill('架构图说明'); await page.keyboard.press('Control+Enter');
 await expect.poll(async () => page.evaluate(() => {
  const state = JSON.parse(localStorage.getItem('fever-demo-v1')!);
  const note = state.manifest.notes.find((n: { title: string }) => n.title === '架构图');
  return JSON.parse(state.contents[note.id]).elements.filter((e: { isDeleted: boolean }) => !e.isDeleted).length;
 })).toBe(2);
 await page.getByTitle('更多笔记操作').click();
 const downloadEvent = page.waitForEvent('download');
 await page.getByRole('button', { name: '导出 .excalidraw' }).click();
 expect((await downloadEvent).suggestedFilename()).toBe('架构图.excalidraw');
 await page.getByRole('button', { name: '新建笔记', exact: true }).first().click();
 await page.getByLabel('笔记标题').fill('绘图文档');
 await page.getByLabel('所属分类').fill('开始使用');
 await page.getByRole('button', { name: '创建笔记', exact: true }).click();
 await page.getByRole('button', { name: '插入 Excalidraw', exact: true }).click();
 await page.getByRole('button', { name: '插入绘图', exact: true }).click();
 await expect(page.locator('.wysiwyg-content .drawing-preview img')).toBeVisible();
 expect(await page.locator('.wysiwyg-content .drawing-preview img').evaluate(img => (window as unknown as { previewSVGs: Map<string, Blob> }).previewSVGs.get((img as HTMLImageElement).src)!.text())).toContain(';base64,');
 await page.getByRole('button', { name: '编辑绘图', exact: true }).click();
 await expect(page.locator('.drawing-canvas')).toBeVisible();
